"""Определение языка по набору символов текста.

Шифры Цезаря, Атбаша, Виженера и аффинный — это замены внутри одного и того же
алфавита (кириллица остаётся кириллицей, латиница — латиницей), поэтому
принадлежность к языку можно установить напрямую по составу символов
шифртекста, не дожидаясь расшифровки. Это надёжнее и проще, чем сравнение
частот через хи-квадрат, которое имеет смысл только для уже читаемого текста.
"""
from __future__ import annotations


def detect_language(text: str) -> str:
    """Определяет язык по первому встреченному символу.
    
    Если текст содержит русскую букву → язык русский.
    Если текст содержит английскую букву → язык английский.
    Если текст не содержит букв → по умолчанию русский.
    """
    if not text:
        return "ru"
    
    # Нормализуем для проверки
    text_lower = text.lower()
    
    # Проверяем наличие русских букв
    has_cyrillic = any('а' <= ch <= 'я' or ch == 'ё' for ch in text_lower)
    if has_cyrillic:
        return "ru"
    
    # Проверяем наличие английских букв
    has_latin = any('a' <= ch <= 'z' for ch in text_lower)
    if has_latin:
        return "en"
    
    # Если нет букв — по умолчанию русский
    return "ru"
